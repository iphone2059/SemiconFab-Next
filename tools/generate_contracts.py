"""Generate C# and TypeScript DTOs from the same JSON Schema definitions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schema = json.loads((ROOT / "contracts/json-schema/contracts.schema.json").read_text(encoding="utf-8"))


def kind(value, language):
    if "$ref" in value:
        return value["$ref"].rsplit("/", 1)[1]
    item = value["type"]
    if isinstance(item, list):
        normal = {**value, "type": next(t for t in item if t != "null")}
        return kind(normal, language) + ("?" if language == "cs" else " | null")
    if item == "array":
        return kind(value["items"], language) + "[]"
    return {"string": "string", "integer": "int" if language == "cs" else "number", "number": "double" if language == "cs" else "number", "boolean": "bool" if language == "cs" else "boolean"}[item]


cs = ["// Generated by tools/generate_contracts.py; do not edit.", "#nullable enable", "namespace Fab.Contracts;", ""]
ts = ["// Generated by tools/generate_contracts.py; do not edit.", ""]
for name, definition in schema["$defs"].items():
    props = definition["properties"]
    cs.append(f"public sealed record {name}(" + ", ".join(f"{kind(v, 'cs')} {k[0].upper() + k[1:]}" for k, v in props.items()) + ");")
    ts.append(f"export interface {name} {{\n" + "\n".join(f"  readonly {k}: {kind(v, 'ts')};" for k, v in props.items()) + "\n}")
def response(name, array=False):
    item = {"$ref": "#/components/schemas/" + name}
    return {"description": "Success", "content": {"application/json": {"schema": {"type": "array", "items": item} if array else item}}}


paths = {}
for route, name, array in [("/api/v1/sites", "SiteDto", True), ("/api/v1/runs", "RunSummary", True), ("/api/v1/runs/{id}", "RunSummary", False), ("/api/v1/runs/{id}/results", "RunResult", False), ("/api/v1/sites/{siteId}/kpi", "SiteKpiDto", False)]:
    parameters = [{"name": key, "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}} for key in ["id", "siteId"] if "{" + key + "}" in route]
    if route.endswith('/kpi'):
        parameters.append({"name": "runId", "in": "query", "required": True, "schema": {"type": "string", "format": "uuid"}})
    paths[route] = {"get": {"parameters": parameters, "responses": {"200": response(name, array), "default": {"description": "ProblemDetails error"}}}}
paths['/api/v1/runs']['post'] = {"parameters": [{"name": "Idempotency-Key", "in": "header", "required": True, "schema": {"type": "string", "maxLength": 128}}], "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/CreateRunRequest"}}}}, "responses": {"202": response('RunSummary'), "default": {"description": "ProblemDetails error"}}}
openapi = {"openapi": "3.1.0", "info": {"title": "SemiconFab Next Development API", "version": "0.1.0", "description": "Loopback Development identity and local file store only; production and OT are unavailable."}, "paths": paths, "security": [{"LocalDevelopment": []}], "components": {"securitySchemes": {"LocalDevelopment": {"type": "apiKey", "in": "header", "name": "X-Fab-Dev-Key"}}, "schemas": json.loads(json.dumps(schema['$defs']).replace('#/$defs/', '#/components/schemas/'))}}
targets = {ROOT / "fab_shared/Generated/Contracts.g.cs": "\n".join(cs) + "\n", ROOT / "web_app/src/contracts.generated.ts": "\n".join(ts) + "\n", ROOT / "contracts/openapi/openapi.json": json.dumps(openapi, ensure_ascii=False, indent=2) + "\n"}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for path, content in targets.items():
    if args.check:
        if not path.exists() or path.read_bytes() != content.encode("utf-8"):
            raise SystemExit(f"Generated contract drift: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
print("Contracts: C# / TypeScript match JSON Schema.")
