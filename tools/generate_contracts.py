"""Generate C# and TypeScript DTOs from the same JSON Schema definitions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schema = json.loads((ROOT / "contracts/json-schema/contracts.schema.json").read_text(encoding="utf-8"))


def kind(value, language):
    if "$ref" in value:
        return value["$ref"].rsplit("/", 1)[1]
    item = value["type"]
    if isinstance(item, list):
        normal = {**value, "type": next(t for t in item if t != "null")}
        return kind(normal, language) + ("?" if language == "cs" else " | null")
    if item == "array":
        return kind(value["items"], language) + "[]"
    if item == "object" and value.get("additionalProperties") is True:
        return "System.Text.Json.JsonElement" if language == "cs" else "Readonly<Record<string, unknown>>"
    if item == "integer":
        # JavaScript numbers are 64-bit floats: only explicit int64 contracts use a
        # C# long; every other integer keeps the historical int mapping.
        return "long" if language == "cs" and value.get("format") == "int64" else ("int" if language == "cs" else "number")
    return {"string": "string", "number": "double" if language == "cs" else "number", "boolean": "bool" if language == "cs" else "boolean"}[item]


def response(definition_name):
    return {"description": "Success", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/" + definition_name}}}}


def array_response(definition_name):
    return {"description": "Success", "content": {"application/json": {"schema": {"type": "array", "items": {"$ref": "#/components/schemas/" + definition_name}}}}}


def problem_response():
    return {"description": "ProblemDetails error"}


cs = ["// Generated by tools/generate_contracts.py; do not edit.", "#nullable enable", "namespace Fab.Contracts;", ""]
ts = ["// Generated by tools/generate_contracts.py; do not edit.", ""]
for name, definition in schema["$defs"].items():
    props = definition["properties"]
    cs.append(f"public sealed record {name}(" + ", ".join(f"{kind(v, 'cs')} {k[0].upper() + k[1:]}" for k, v in props.items()) + ");")
    ts.append(f"export interface {name} {{\n" + "\n".join(f"  readonly {k}: {kind(v, 'ts')};" for k, v in props.items()) + "\n}")


paths = {}
for route, name, array in [("/api/v1/sites", "SiteDto", True), ("/api/v1/runs", "RunSummary", True), ("/api/v1/runs/{id}", "RunSummary", False), ("/api/v1/runs/{id}/results", "RunResult", False), ("/api/v1/sites/{siteId}/kpi", "SiteKpiDto", False)]:
    parameters = [{"name": key, "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}} for key in ["id", "siteId"] if "{" + key + "}" in route]
    if route.endswith('/kpi'):
        parameters.append({"name": "runId", "in": "query", "required": True, "schema": {"type": "string", "format": "uuid"}})
    paths[route] = {"get": {"parameters": parameters, "responses": {"200": array_response(name) if array else response(name), "default": problem_response()}}}
paths['/api/v1/runs']['post'] = {"parameters": [{"name": "Idempotency-Key", "in": "header", "required": True, "schema": {"type": "string", "maxLength": 128}}], "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": "#/components/schemas/CreateRunRequest"}}}}, "responses": {"202": response('RunSummary'), "default": problem_response()}}
paths['/api/v1/catalog'] = {"get": {"parameters": [
    {"name": "domain", "in": "query", "schema": {"type": "string", "enum": ["ALL", "FAB", "OSAT"]}},
    {"name": "category", "in": "query", "schema": {"type": "string"}},
    {"name": "q", "in": "query", "schema": {"type": "string", "maxLength": 200}}],
    "responses": {"200": response('CatalogPageDto'), "default": problem_response()}}}
paths['/api/v1/catalog/{id}'] = {"get": {"parameters": [{"name": "id", "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}}],
    "responses": {"200": response('CatalogEntryDto'), "default": problem_response()}}}

# Phase D durable command recovery endpoints (ADR-008 2.2). The command stream itself is
# text/event-stream and deliberately stays out of this JSON-only registry.
paths['/api/v1/sites/{siteId}/fabs/{fabId}/commands'] = {"get": {
    "description": "Authoritative command listing for one FAB. Browser refresh / severe replay gaps use this to rebuild tracked commands; it is the only recovery entry point for unacknowledged commands.",
    "parameters": [
        {"name": "siteId", "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}},
        {"name": "fabId", "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}},
        {"name": "status", "in": "query", "schema": {"type": "string", "enum": ["active", "terminal", "all"]}},
        {"name": "afterRevision", "in": "query", "schema": {"type": "integer", "minimum": -1}}],
    "responses": {"200": response('CommandRecoveryListDto'), "default": problem_response()}}}
paths['/api/v1/sites/{siteId}/fabs/{fabId}/command-journal'] = {"get": {
    "description": "Journal replay page for one FAB and one epoch (ADR-010 3). epoch is mandatory: a missing/invalid epoch is a 400 journal-cursor-invalid ProblemDetails; a stale epoch is a 409 journal-epoch-mismatch ProblemDetails that forces the client to reconcile authoritative command state. nextAfterSequence is the next page cursor (last event sequence, or the authoritative watermark when a FAB filter yields an empty page).",
    "parameters": [
        {"name": "siteId", "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}},
        {"name": "fabId", "in": "path", "required": True, "schema": {"type": "string", "format": "uuid"}},
        {"name": "epoch", "in": "query", "required": True, "schema": {"type": "string", "format": "uuid"}},
        {"name": "afterSequence", "in": "query", "schema": {"type": "integer", "format": "int64", "minimum": 0}},
        {"name": "limit", "in": "query", "schema": {"type": "integer", "minimum": 1, "maximum": 1000}}],
    "responses": {
        "200": response('CommandJournalPageDto'),
        "400": {"description": "ProblemDetails error with code journal-cursor-invalid", "content": {"application/problem+json": {"schema": {"type": "object", "additionalProperties": True}}}},
        "409": {"description": "Stale journal epoch", "content": {"application/problem+json": {"schema": {"$ref": "#/components/schemas/JournalEpochMismatchDto"}}}},
        "default": problem_response()}}}

openapi = {"openapi": "3.1.0", "info": {"title": "SemiconFab Next Development API", "version": "0.1.0", "description": "Loopback Development identity and local file store only; production and OT are unavailable."}, "paths": paths, "security": [{"LocalDevelopment": []}], "components": {"securitySchemes": {"LocalDevelopment": {"type": "apiKey", "in": "header", "name": "X-Fab-Dev-Key"}}, "schemas": json.loads(json.dumps(schema['$defs']).replace('#/$defs/', '#/components/schemas/'))}}
targets = {ROOT / "fab_shared/src/Generated/Contracts.g.cs": "\n".join(cs) + "\n", ROOT / "web_app/src/generated/contracts.generated.ts": "\n".join(ts) + "\n", ROOT / "contracts/openapi/openapi.json": json.dumps(openapi, ensure_ascii=False, indent=2) + "\n"}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for path, content in targets.items():
    if args.check:
        if not path.exists() or path.read_bytes() != content.encode("utf-8"):
            raise SystemExit(f"Generated contract drift: {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
print("Contracts: C# / TypeScript match JSON Schema.")