// Generates the frozen en/zh translation map consumed by the Twin UI.
// Input is the C1 inventory web_app/assets/original-twin-i18n.json (only en + zh-CN bytes).
// Output web_app/src/generated/twin-translations.generated.ts is deterministic; use --check for CI.
//
// Determinism and collision policy:
//   1. source entries are fixture.keys in document order, then fixture.dynamic in source-line order;
//   2. identical zh strings collapse to one entry; the FIRST occurrence in that order wins;
//   3. zh strings that map to more than one en value are counted in the generator summary as
//      distinct en values in first-appearance order (the first element is the emitted winner);
//   4. emitted keys are sorted by UTF-16 code unit (locale-independent), not localeCompare.
// No locale other than en/zh-CN is ever serialized.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const fixturePath = path.join(root, 'web_app/assets/original-twin-i18n.json');
const destinationPath = path.join(root, 'web_app/src/generated/twin-translations.generated.ts');

const sha256 = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');
const compareText = (left, right) => (left < right ? -1 : left > right ? 1 : 0);
const isNonEmptyString = (value) => typeof value === 'string' && value.length > 0;

function fail(message) {
  throw new Error(message);
}

const fixtureBuffer = fs.readFileSync(fixturePath);
const fixture = JSON.parse(fixtureBuffer.toString('utf8'));
if (fixture.locales.length !== 2 || fixture.locales[0] !== 'en' || fixture.locales[1] !== 'zh-CN') {
  fail('Fixture locales must be exactly [en, zh-CN]');
}
if (fixture.excludedLocales.length !== 7) fail('Fixture must declare the seven excluded locales');
for (const locale of fixture.excludedLocales) {
  if (fixture.locales.includes(locale)) fail('Excluded locale leaked into the emitted locales: ' + locale);
}

const sourceEntries = [];
for (const entry of fixture.keys) {
  if (!isNonEmptyString(entry.key) || !isNonEmptyString(entry.zhCN) || !isNonEmptyString(entry.en)) continue;
  sourceEntries.push({ zhCN: entry.zhCN, en: entry.en, origin: 'keys.' + entry.key });
}
for (const entry of fixture.dynamic) {
  if (!isNonEmptyString(entry.id) || !isNonEmptyString(entry.zhCN) || !isNonEmptyString(entry.en)) continue;
  sourceEntries.push({ zhCN: entry.zhCN, en: entry.en, origin: 'dynamic.' + entry.id });
}
if (sourceEntries.length === 0) fail('Fixture produced no translatable entries');

const groups = new Map();
for (const entry of sourceEntries) {
  if (!groups.has(entry.zhCN)) groups.set(entry.zhCN, []);
  groups.get(entry.zhCN).push(entry);
}

const emitted = {};
const collisions = {};
let collapsedDuplicates = 0;
const sortedZh = [...groups.keys()].sort(compareText);
for (const zhCN of sortedZh) {
  const group = groups.get(zhCN);
  const distinctEnglish = [];
  for (const entry of group) {
    if (!distinctEnglish.includes(entry.en)) distinctEnglish.push(entry.en);
  }
  collapsedDuplicates += group.length - 1;
  emitted[zhCN] = distinctEnglish[0];
  if (distinctEnglish.length > 1) collisions[zhCN] = distinctEnglish;
}

const provenance = {
  generator: 'tools/build_twin_translations.cjs',
  generatorCommand: 'node tools/build_twin_translations.cjs',
  fixture: 'web_app/assets/original-twin-i18n.json',
  fixtureSha256: sha256(fixtureBuffer),
  sourceSha256: {
    'twin.html': fixture.source['twin.html'].sha256,
    'js/translations.js': fixture.source['js/translations.js'].sha256,
    'js/i18n.js': fixture.source['js/i18n.js'].sha256,
  },
  locales: ['en', 'zh-CN'],
  excludedLocales: fixture.excludedLocales,
  fixtureCounts: fixture.counts,
  entries: {
    sourcePairs: sourceEntries.length,
    uniqueZh: sortedZh.length,
    collapsedDuplicates,
    collisions: Object.keys(collisions).length,
  },
  collisionPolicy: 'first occurrence in fixture order wins; all distinct en values are listed in first-appearance order',
};

const header = [
  '// AUTO-GENERATED by tools/build_twin_translations.cjs from web_app/assets/original-twin-i18n.json.',
  '// DO NOT EDIT. Regenerate with: node tools/build_twin_translations.cjs',
  '//',
  '// Frozen provenance: twin.html ' + provenance.sourceSha256['twin.html'],
  '//   js/translations.js ' + provenance.sourceSha256['js/translations.js'],
  '//   js/i18n.js ' + provenance.sourceSha256['js/i18n.js'],
  '// Fixture counts: keys ' + String(fixture.counts.keys) + ', dynamic ' + String(fixture.counts.dynamic) +
    ', missing ' + String(fixture.counts.missing) + ', skipped ' + String(fixture.counts.skipped) + '.',
  '// Generated: ' + String(sourceEntries.length) + ' source pairs -> ' + String(sortedZh.length) +
    ' unique zh entries, ' + String(Object.keys(collisions).length) + ' collisions, ' + String(collapsedDuplicates) +
    ' collapsed duplicates.',
  '// Locale policy: only en + zh-CN bytes are serialized; the seven other frozen locales are intentionally absent.',
  '// Collision policy: ' + provenance.collisionPolicy + '.',
  '',
].join('\n');

const englishLines = sortedZh.map((zhCN) => '  ' + JSON.stringify(zhCN) + ': ' + JSON.stringify(emitted[zhCN]) + ',');
const output = header +
  'export const GENERATED_TWIN_EN: Readonly<Record<string, string>> = {\n' +
  englishLines.join('\n') + '\n' +
  '};\n';

if (process.argv.includes('--check')) {
  let existing;
  try {
    existing = fs.readFileSync(destinationPath, 'utf8');
  } catch (error) {
    fail('Generated twin translations are missing; run node tools/build_twin_translations.cjs');
  }
  if (existing !== output) {
    fail('Generated twin translations drift: ' + path.relative(root, destinationPath));
  }
  console.log('Twin translations stable: ' + sortedZh.length + ' entries, ' +
    Object.keys(collisions).length + ' collisions, ' + sourceEntries.length + ' source pairs');
} else {
  fs.mkdirSync(path.dirname(destinationPath), { recursive: true });
  fs.writeFileSync(destinationPath, output);
  console.log('Generated twin translations: ' + sortedZh.length + ' entries, ' +
    Object.keys(collisions).length + ' collisions, ' + sourceEntries.length + ' source pairs, ' +
    collapsedDuplicates + ' collapsed duplicates -> ' + path.relative(root, destinationPath));
}
