const LITHO_AIR_SHOWER_ID = 'fac.airshower.litho.1';

function statusKeyOf(
  phase: PatrolPhase,
  waypointIndex: number,
  statusTextZh: string,
  waypoints: readonly PatrolWaypoint[],
): string {
  if (phase !== 'PATROL_WAYPOINTS') return phase;
  const waypoint = waypoints[waypointIndex];
  const inspecting = waypoint !== undefined && statusTextZh.startsWith(waypoint.nameZh + ' (');
  return (inspecting ? 'inspect:' : 'travel:') + waypointIndex;
}

export function createPersonnelTimeline(scenario: PersonnelScenario): PersonnelTimeline {
  const waypoints = PATROL_WAYPOINTS;
  const preserved = scenario.chamberUserDataMode === 'preserved';
  const lcg = createLcg(scenario.seed);

  // Frozen build order random draws: createAirlockVortexParticles (5 draws per
  // particle) then one createAirShower timer draw per chamber.
  const vortexParticles: VortexRuntimeParticle[] = [];
  for (let index = 0; index < VORTEX_PARTICLE_COUNT; index += 1) {
    const angle = lcg.random() * Math.PI * 2;
    const radius = 0.35 + lcg.random() * 0.75;
    const y = 0.2 + lcg.random() * 2.2;
    const speed = 4.5 + lcg.random() * 5.0;
    const vy = -0.8 - lcg.random() * 1.5;
    vortexParticles.push({
      angle,
      radius,
      y,
      speed,
      vy,
      px: Math.fround(VORTEX_ORIGIN.x + Math.cos(angle) * radius),
      py: Math.fround(y),
      pz: Math.fround(VORTEX_ORIGIN.z + Math.sin(angle) * radius),
    });
  }
  const chambers: ChamberRuntime[] = AIR_SHOWERS.map((spec) => {
    const constructedTimer = lcg.random() * 5.0;
    return {
      spec,
      constructedTimer,
      timer: preserved ? constructedTimer : Number.NaN,
      retainedUserData: preserved,
      isPurging: false,
      indicators: [
        {
          color: RENDER_COLORS.indicatorReady,
          emissive: RENDER_COLORS.indicatorReady,
          emissiveIntensity: 0.8,
        },
        {
          color: RENDER_COLORS.indicatorReady,
          emissive: RENDER_COLORS.indicatorReady,
          emissiveIntensity: 0.8,
        },
      ],
      jets: [0, 1, 2, 3].map(() => ({ opacity: 0, scale: 1 })),
      innerLight: 0.4,
      labelSpriteY: spec.height + 1.2,
    };
  });
  const seedAfterBuild = lcg.seed();

  const vortex = { opacity: 0.0, particles: vortexParticles };

  const patrol: PatrolRuntime = {
    state: 'APPROACH_AIRLOCK',
    stateTimer: 0,
    waypointIndex: 0,
    walkPhase: 0,
    statusTextZh: '正在步向黄光风淋气闸',
    statusTextEn: 'Approaching Litho Airlock',
    position: { x: -13.0, y: 0.0, z: 8.5 },
    rotationY: -Math.PI / 2,
  };
  // Frozen createBunnySuitOperator initial tablet screen material (9424-9437).
  const screen: { color: number; emissive: number; emissiveIntensity: number } = {
    color: RENDER_COLORS.idleScreen,
    emissive: RENDER_COLORS.idleScreenEmissive,
    emissiveIntensity: 0.85,
  };
  const staff = PERSONNEL.filter((entry) => !entry.isPatrol).map((entry) => ({
    config: entry,
    y: entry.y,
  }));
  const statusSpriteY = { value: STATUS_SPRITE_BASE_Y };
  const legs = { left: 0, right: 0 };
  const arms = { left: 0, right: 0 };
  const lithoChamber =
    chambers.find((chamber) => chamber.spec.id === LITHO_AIR_SHOWER_ID) ?? null;

  let tick = 0;
  let clockMs = scenario.clockStartMs;
  // Full diagnostic history is opt-in (tests/acceptance only); production keeps
  // counters and the fixed-size waypoint state instead of O(time) arrays.
  const trace = scenario.trace;
  const traceEnabled = trace !== undefined && trace.enabled !== false;
  const eventsLimit = traceEnabled ? Math.max(0, trace?.maxEvents ?? 0) : 0;
  const phaseChangesLimit = traceEnabled ? Math.max(0, trace?.maxPhaseChanges ?? 0) : 0;
  const purgesLimit = traceEnabled ? Math.max(0, trace?.maxPurges ?? 0) : 0;
  const events: PersonnelEvent[] = [];
  const phaseSequence: PatrolPhase[] = [];
  const phaseTicks: Record<PatrolPhase, number> = {
    APPROACH_AIRLOCK: 0,
    ENTER_AIRLOCK: 0,
    AIR_SHOWER_CYCLE: 0,
    EXIT_TO_LITHO: 0,
    PATROL_WAYPOINTS: 0,
    RETURN_AIRLOCK: 0,
  };
  const purges: PurgeRecord[] = [];
  const waypointRuntime: WaypointRuntime[] = waypoints.map(() => ({
    ticks: 0,
    reachedTick: null,
    arrivals: 0,
  }));
  let eventCount = 0;
  let phaseChangeCount = 0;
  let purgeCount = 0;
  let purgeTicks = 0;
  let currentPurge: PurgeRecord | null = null;
  let previousPhase: PatrolPhase = patrol.state;
  let previousStatusKey = statusKeyOf(
    patrol.state,
    patrol.waypointIndex,
    patrol.statusTextZh,
    waypoints,
  );
  let previousWaypointIndex = patrol.waypointIndex;
  let previousArrivalIndex: number | null = null;
  let previousScreen = screen.color;
  let previousVortexOpacity = vortex.opacity;
  const previousChamberState = chambers.map(() => ({ purging: false, cycleBlowing: false }));
  let previousStateTimer = 0;
  let lastTick = 0;

  // Ring-buffer append: with a positive capacity the oldest recorded entry is
  // dropped, so an opted-in trace is bounded too. Counters stay cumulative.
  const record = <T>(list: T[], value: T, limit: number): void => {
    list.push(value);
    if (limit > 0 && list.length > limit) list.splice(0, list.length - limit);
  };

  const pushEvent = (fields: Omit<PersonnelEvent, 'tick' | 'time'>): void => {
    eventCount += 1;
    if (traceEnabled) record(events, { tick, time: round(tick * scenario.dt), ...fields }, eventsLimit);
  };

  const walkTowards = (targetX: number, targetZ: number, speed: number): number => {
    const dx = targetX - patrol.position.x;
    const dz = targetZ - patrol.position.z;
    const distance = Math.hypot(dx, dz);
    if (distance > 0.05) {
      const stepLength = Math.min(speed * scenario.dt, distance);
      patrol.position.x += (dx / distance) * stepLength;
      patrol.position.z += (dz / distance) * stepLength;
      const targetAngle = Math.atan2(dx, dz);
      let diffAngle = targetAngle - patrol.rotationY;
      while (diffAngle < -Math.PI) diffAngle += Math.PI * 2;
      while (diffAngle > Math.PI) diffAngle -= Math.PI * 2;
      patrol.rotationY += diffAngle * Math.min(scenario.dt * 6.0, 1.0);
      patrol.walkPhase += scenario.dt * 8.0;
      if (preserved) {
        legs.left = Math.sin(patrol.walkPhase) * 0.42;
        legs.right = -Math.sin(patrol.walkPhase) * 0.42;
        arms.left = 0.55 + Math.cos(patrol.walkPhase) * 0.15;
        arms.right = 0.55 - Math.cos(patrol.walkPhase) * 0.15;
      }
      patrol.position.y = Math.abs(Math.sin(patrol.walkPhase * 2)) * 0.03;
    } else {
      if (preserved) {
        legs.left = 0;
        legs.right = 0;
      }
      patrol.position.y = 0;
    }
    return distance;
  };

  const setIndicatorState = (chamber: ChamberRuntime, color: number, intensity: number): void => {
    for (const indicator of chamber.indicators) {
      indicator.color = color;
      indicator.emissive = color;
      indicator.emissiveIntensity = intensity;
    }
  };

  const behaviorTreeStep = (): void => {
    const nowMs = clockMs;
    const nowSec = nowMs * 0.001;
    patrol.stateTimer += scenario.dt;

    switch (patrol.state) {
      case 'APPROACH_AIRLOCK': {
        patrol.statusTextZh = '正在步向黄光风淋气闸';
        patrol.statusTextEn = 'Approaching Litho Airlock Entry';
        const distance = walkTowards(-16.5, 4.8, 1.35);
        if (distance < 0.25) {
          patrol.state = 'ENTER_AIRLOCK';
          patrol.stateTimer = 0;
        }
        break;
      }
      case 'ENTER_AIRLOCK': {
        patrol.statusTextZh = '步入洁净风淋气闸·双门互锁';
        patrol.statusTextEn = 'Entering Airlock · Interlock Engaged';
        const distance = walkTowards(-16.5, 3.0, 1.1);
        if (distance < 0.15) {
          patrol.state = 'AIR_SHOWER_CYCLE';
          patrol.stateTimer = 0;
          if (lithoChamber !== null) lithoChamber.isPurging = true;
        }
        break;
      }
      case 'AIR_SHOWER_CYCLE': {
        patrol.statusTextZh =
          '高速除尘吹淋中 28 m/s (' +
          Math.max(0, PURGE_SECONDS - patrol.stateTimer).toFixed(1) +
          's)';
        patrol.statusTextEn =
          'HEPA Air Purging 28 m/s (' +
          Math.max(0, PURGE_SECONDS - patrol.stateTimer).toFixed(1) +
          's)';
        patrol.rotationY += scenario.dt * 1.4;
        if (preserved) {
          legs.left = 0;
          legs.right = 0;
        }
        patrol.position.y = 0;
        if (lithoChamber !== null && lithoChamber.retainedUserData) {
          const flash = Math.sin(nowSec * 22) > 0;
          const alertColor = flash ? RENDER_COLORS.purgeAlertRed : RENDER_COLORS.purgeAlertAmber;
          setIndicatorState(lithoChamber, alertColor, flash ? 1.8 : 0.3);
          lithoChamber.jets.forEach((jet, index) => {
            jet.opacity = 0.85 + Math.sin(nowSec * 28 + index) * 0.15;
            jet.scale = 1.15 + Math.sin(nowSec * 35 + index) * 0.25;
          });
          lithoChamber.innerLight = 1.8 + Math.sin(nowSec * 20) * 0.5;
        }
        if (preserved) {
          screen.color = RENDER_COLORS.purgeScreen;
          screen.emissive = RENDER_COLORS.purgeScreenEmissive;
        }
        vortex.opacity = 0.85;
        for (const particle of vortex.particles) {
          particle.angle += scenario.dt * particle.speed;
          particle.y += scenario.dt * particle.vy;
          if (particle.y <= 0.1) particle.y = 2.4;
          particle.px = Math.fround(VORTEX_ORIGIN.x + Math.cos(particle.angle) * particle.radius);
          particle.py = Math.fround(particle.y);
          particle.pz = Math.fround(VORTEX_ORIGIN.z + Math.sin(particle.angle) * particle.radius);
        }
        if (patrol.stateTimer >= PURGE_SECONDS) {
          patrol.state = 'EXIT_TO_LITHO';
          patrol.stateTimer = 0;
          if (lithoChamber !== null) lithoChamber.isPurging = false;
          vortex.opacity = 0.0;
        }
        break;
      }
      case 'EXIT_TO_LITHO': {
        patrol.statusTextZh = '吹淋完毕·安全绿灯放行·步入黄光区';
        patrol.statusTextEn = 'Purge Complete · Safe Green · Entering Litho';
        if (lithoChamber !== null && lithoChamber.retainedUserData) {
          setIndicatorState(lithoChamber, RENDER_COLORS.indicatorReady, 1.2);
          lithoChamber.jets.forEach((jet) => {
            jet.opacity = 0.0;
          });
        }
        if (preserved) {
          screen.color = RENDER_COLORS.idleScreen;
          screen.emissive = RENDER_COLORS.idleScreenEmissive;
        }
        const distance = walkTowards(-18.5, -2.0, 1.3);
        if (distance < 0.25) {
          patrol.state = 'PATROL_WAYPOINTS';
          patrol.waypointIndex = 0;
          patrol.stateTimer = 0;
        }
        break;
      }
      case 'PATROL_WAYPOINTS': {
        const waypoint = waypoints[patrol.waypointIndex];
        const distance = walkTowards(waypoint.x, waypoint.z, 1.35);
        if (distance < 0.35) {
          patrol.statusTextZh =
            waypoint.nameZh +
            ' (' +
            Math.max(0, waypoint.duration - patrol.stateTimer).toFixed(1) +
            's)';
          patrol.statusTextEn =
            waypoint.nameEn +
            ' (' +
            Math.max(0, waypoint.duration - patrol.stateTimer).toFixed(1) +
            's)';
          if (preserved) {
            legs.left = 0;
            legs.right = 0;
            arms.left = 0.85;
            arms.right = 0.85;
            screen.emissiveIntensity = 0.9 + Math.sin(nowMs * 0.01) * 0.35;
          }
          patrol.position.y = 0;
          patrol.rotationY = waypoint.inspectAngle;
          if (patrol.stateTimer >= waypoint.duration) {
            patrol.waypointIndex += 1;
            patrol.stateTimer = 0;
            if (patrol.waypointIndex >= waypoints.length) {
              patrol.state = 'RETURN_AIRLOCK';
            }
          }
        } else {
          patrol.statusTextZh = '正在前往: ' + waypoint.nameZh;
          patrol.statusTextEn = 'Heading to: ' + waypoint.nameEn;
        }
        break;
      }
      case 'RETURN_AIRLOCK': {
        patrol.statusTextZh = '黄光区巡检完成·步出风淋气闸返回主通道';
        patrol.statusTextEn = 'Litho Patrol Completed · Returning to Corridor';
        const distance = walkTowards(-13.0, 8.5, 1.4);
        if (distance < 0.4) {
          patrol.state = 'APPROACH_AIRLOCK';
          patrol.stateTimer = 0;
        }
        break;
      }
    }

    if (preserved) {
      statusSpriteY.value = 2.15 + Math.sin(nowMs * 0.003) * 0.04;
    }
  };

  const airShowerCycleStep = (): void => {
    const nowMs = clockMs;
    const nowSec = nowMs * 0.001;
    for (const chamber of chambers) {
      // Frozen standby block: skip chambers currently purged by the patrol tree.
      if (chamber.isPurging) continue;
      if (preserved) {
        chamber.timer += AIR_SHOWER_CYCLE_STEP;
      } else {
        // As-built, userData was replaced by the catalog record: timer is
        // undefined, so the frozen += 0.016 poisons it to NaN and the whole
        // standby/blowing animation is unreachable.
        chamber.timer = Number.NaN;
      }
      if (preserved) {
        const cycleTime = chamber.timer % AIR_SHOWER_STANDBY_SECONDS;
        const isBlowing = cycleTime > AIR_SHOWER_BLOW_START_SECONDS;
        if (isBlowing) {
          const flash = Math.sin(nowSec * 16) > 0;
          const activeColor = chamber.spec.isAmber
            ? flash
              ? RENDER_COLORS.amberBlowBright
              : RENDER_COLORS.amberBlowDim
            : flash
              ? RENDER_COLORS.mainBlowBright
              : RENDER_COLORS.mainBlowDim;
          setIndicatorState(chamber, activeColor, flash ? 1.6 : 0.2);
          chamber.jets.forEach((jet, index) => {
            jet.opacity = 0.55 + Math.sin(nowSec * 28 + index * 1.5) * 0.25;
            jet.scale = 0.9 + Math.sin(nowSec * 32 + index * 2.0) * 0.2;
          });
          chamber.innerLight = 1.4 + Math.sin(nowSec * 20) * 0.5;
        } else {
          setIndicatorState(chamber, RENDER_COLORS.indicatorReady, 0.8);
          chamber.jets.forEach((jet) => {
            jet.opacity = 0.0;
          });
          chamber.innerLight = 0.35;
        }
        chamber.labelSpriteY =
          (chamber.spec.height || 2.8) +
          1.2 +
          Math.sin(nowSec * 2.2 + chamber.spec.position.x) * 0.08;
      }
    }
  };

  const breathStep = (): void => {
    const breath = Math.sin(clockMs * 0.0025) * 0.005;
    for (const staffEntry of staff) staffEntry.y = breath;
  };

  const readFrame = (): PersonnelFrame => {
    const actors: ActorFrame[] = [];
    for (const staffEntry of staff) {
      actors.push({
        x: round(staffEntry.config.x),
        y: round(staffEntry.y),
        z: round(staffEntry.config.z),
        rotY: round(staffEntry.config.rotY),
        walkPhase: 0,
      });
    }
    actors.push({
      x: round(patrol.position.x),
      y: round(patrol.position.y),
      z: round(patrol.position.z),
      rotY: round(patrol.rotationY),
      walkPhase: round(patrol.walkPhase),
    });
    return {
      tick,
      time: round(tick * scenario.dt),
      actors,
      patrol: {
        phase: patrol.state,
        stateTimer: round(patrol.stateTimer),
        waypointIndex: patrol.waypointIndex,
        statusKey: statusKeyOf(patrol.state, patrol.waypointIndex, patrol.statusTextZh, waypoints),
        statusTextZh: patrol.statusTextZh,
        statusTextEn: patrol.statusTextEn,
        screenColor: screen.color,
        screenEmissive: screen.emissive,
        screenEmissiveIntensity: round(screen.emissiveIntensity),
        statusSpriteY: round(statusSpriteY.value),
        statusSpriteVisible: true,
        legs: { left: round(legs.left), right: round(legs.right) },
        arms: { left: round(arms.left), right: round(arms.right) },
      },
      airShowers: chambers.map((chamber) => ({
        id: chamber.spec.id,
        timer: Number.isFinite(chamber.timer) ? round(chamber.timer) : null,
        cycleTime: Number.isFinite(chamber.timer)
          ? round(chamber.timer % AIR_SHOWER_STANDBY_SECONDS)
          : null,
        cycleBlowing:
          Number.isFinite(chamber.timer) &&
          chamber.timer % AIR_SHOWER_STANDBY_SECONDS > AIR_SHOWER_BLOW_START_SECONDS,
        isPurging: chamber.isPurging,
        indicator: {
          color: chamber.indicators[0].color,
          emissive: chamber.indicators[0].emissive,
          intensity: round(chamber.indicators[0].emissiveIntensity),
        },
        jets: chamber.jets.map((jet) => ({
          opacity: round(jet.opacity),
          scale: round(jet.scale),
        })),
        innerLight: round(chamber.innerLight),
        labelSpriteY: round(chamber.labelSpriteY),
      })),
      vortexOpacity: round(vortex.opacity),
    };
  };

  const emitEvents = (current: PersonnelFrame): void => {
    const statusKey = current.patrol.statusKey;
    if (patrol.state !== previousPhase) {
      pushEvent({
        type: 'patrol-phase',
        from: previousPhase,
        to: patrol.state,
        statusKey,
        statusTextZh: patrol.statusTextZh,
        statusTextEn: patrol.statusTextEn,
        x: current.actors[PERSONNEL.length - 1].x,
        z: current.actors[PERSONNEL.length - 1].z,
      });
      phaseChangeCount += 1;
      if (traceEnabled) record(phaseSequence, patrol.state, phaseChangesLimit);
    }
    if (statusKey !== previousStatusKey) {
      pushEvent({
        type: 'patrol-status',
        from: previousStatusKey,
        to: statusKey,
        statusTextZh: patrol.statusTextZh,
        statusTextEn: patrol.statusTextEn,
      });
    }
    if (patrol.waypointIndex !== previousWaypointIndex) {
      pushEvent({
        type: 'waypoint-index',
        from: previousWaypointIndex,
        to: patrol.waypointIndex,
        statusKey,
      });
    }
    let arrivalIndex: number | null = null;
    for (let index = 0; index < waypoints.length; index += 1) {
      if (patrol.statusTextZh.startsWith(waypoints[index].nameZh + ' (')) {
        arrivalIndex = index;
        break;
      }
    }
    // Record the inspection arrival once per edge, not once per dwell tick: the
    // cumulative arrival counter and the diagnostic event share the same edge.
    if (arrivalIndex !== null && arrivalIndex !== previousArrivalIndex) {
      waypointRuntime[arrivalIndex].arrivals += 1;
      if (waypointRuntime[arrivalIndex].reachedTick === null) {
        waypointRuntime[arrivalIndex].reachedTick = tick;
      }
      pushEvent({
        type: 'waypoint-reached',
        index: arrivalIndex,
        waypointIndex: patrol.waypointIndex,
        indexAdvancedInSameCall: patrol.waypointIndex !== arrivalIndex,
        stateTimer: current.patrol.stateTimer,
        duration: waypoints[arrivalIndex].duration,
        statusTextZh: patrol.statusTextZh,
        statusTextEn: patrol.statusTextEn,
      });
    }
    previousArrivalIndex = arrivalIndex;
    if (screen.color !== previousScreen) {
      pushEvent({
        type: 'tablet-screen',
        color: screen.color,
        emissive: screen.emissive,
        emissiveIntensity: round(screen.emissiveIntensity),
      });
      previousScreen = screen.color;
    }
    for (let index = 0; index < current.airShowers.length; index += 1) {
      const chamberFrame = current.airShowers[index];
      const before = previousChamberState[index];
      const chamberName = index === 0 ? 'main' : 'litho';
      if (chamberFrame.isPurging !== before.purging) {
        pushEvent({
          type: 'air-shower-purge',
          chamber: chamberName,
          purging: chamberFrame.isPurging,
        });
      }
      if (!chamberFrame.isPurging && chamberFrame.cycleBlowing !== before.cycleBlowing) {
        pushEvent({
          type: 'air-shower-blow',
          chamber: chamberName,
          blowing: chamberFrame.cycleBlowing,
          cycleTime: chamberFrame.cycleTime,
        });
      }
      previousChamberState[index] = {
        purging: chamberFrame.isPurging,
        cycleBlowing: chamberFrame.cycleBlowing,
      };
    }
    if (current.vortexOpacity !== previousVortexOpacity) {
      pushEvent({
        type: 'vortex-opacity',
        from: previousVortexOpacity,
        to: current.vortexOpacity,
      });
      previousVortexOpacity = current.vortexOpacity;
    }
  };

  const trackStats = (current: PersonnelFrame): void => {
    if (
      patrol.state !== previousPhase &&
      previousPhase === 'AIR_SHOWER_CYCLE' &&
      currentPurge !== null
    ) {
      currentPurge.endTick = tick;
      currentPurge.ticks = tick - currentPurge.startTick;
      currentPurge.seconds = round(currentPurge.ticks * scenario.dt);
      currentPurge.lastStateTimer = round(previousStateTimer);
      purgeCount += 1;
      if (traceEnabled) record(purges, currentPurge, purgesLimit);
      currentPurge = null;
    }
    if (patrol.state === 'AIR_SHOWER_CYCLE') {
      purgeTicks += 1;
      if (currentPurge === null) {
        currentPurge = {
          startTick: tick,
          endTick: -1,
          ticks: 0,
          seconds: 0,
          ticksInState: 0,
          lastStateTimer: 0,
        };
      }
      currentPurge.ticksInState += 1;
    }
    if (patrol.state === 'PATROL_WAYPOINTS' && patrol.waypointIndex < waypoints.length) {
      waypointRuntime[patrol.waypointIndex].ticks += 1;
    }
    phaseTicks[patrol.state] += 1;
    previousPhase = patrol.state;
    previousStatusKey = current.patrol.statusKey;
    previousWaypointIndex = patrol.waypointIndex;
    previousStateTimer = current.patrol.stateTimer;
    lastTick = tick;
  };

  const initialFrame = readFrame();

  return {
    get tick() {
      return tick;
    },
    step(): void {
      tick += 1;
      clockMs = scenario.clockStartMs + tick * scenario.clockMsPerTick;
      behaviorTreeStep();
      breathStep();
      airShowerCycleStep();
      const current = readFrame();
      emitEvents(current);
      trackStats(current);
    },
    readFrame,
    readInitialFrame(): PersonnelFrame {
      return initialFrame;
    },
    readVortexParticles(): VortexParticleRender[] {
      return vortex.particles.map((particle) => ({
        angle: particle.angle,
        y: particle.y,
        position: { x: particle.px, y: particle.py, z: particle.pz },
      }));
    },
    readEvents(): PersonnelEvent[] {
      return events.slice();
    },
    readPhases(): PhaseSummary {
      return {
        sequence: phaseSequence.slice(),
        ticks: { ...phaseTicks },
        purgeTicks,
        purgeSeconds: round(purgeTicks * scenario.dt),
        purges: purges.slice(),
      };
    },
    readTraceCounters(): PersonnelTraceCounters {
      return {
        traceEnabled,
        traceBounded: eventsLimit > 0 || phaseChangesLimit > 0 || purgesLimit > 0,
        events: eventCount,
        phaseChanges: phaseChangeCount,
        purges: purgeCount,
        waypointArrivals: waypointRuntime.map((entry) => entry.arrivals),
      };
    },
    readWaypointTrace(): WaypointTraceEntry[] {
      return waypoints.map((waypoint, index) => ({
        index,
        x: waypoint.x,
        z: waypoint.z,
        targetTool: waypoint.targetTool,
        nameZh: waypoint.nameZh,
        nameEn: waypoint.nameEn,
        duration: waypoint.duration,
        inspectAngle: waypoint.inspectAngle,
        ticks: waypointRuntime[index].ticks,
        reachedTick: waypointRuntime[index].reachedTick,
      }));
    },
    readStats(): PersonnelStats {
      return {
        seedAfter: seedAfterBuild,
        ticks: scenario.ticks,
        dt: scenario.dt,
        personnel: PERSONNEL.length,
        actors: PERSONNEL.length,
        chambers: chambers.length,
        vortexParticles: VORTEX_PARTICLE_COUNT,
        events: eventCount,
        phaseChanges: phaseChangeCount,
        purgeTicks,
        purgeSeconds: round(purgeTicks * scenario.dt),
        purges: purgeCount,
        waypointsReached: waypointRuntime.filter((entry) => entry.reachedTick !== null).length,
        lastTick,
      };
    },
    readPersonnel(): PersonnelConfig[] {
      return PERSONNEL.map((entry) => ({
        ...entry,
        x: round(entry.x),
        y: round(entry.y),
        z: round(entry.z),
        rotY: round(entry.rotY),
      }));
    },
    readVortexInitial(): VortexInitial {
      return {
        count: VORTEX_PARTICLE_COUNT,
        opacity: 0.0,
        size: 0.22,
        color: RENDER_COLORS.vortexPoints,
        blending: 2,
        particles: vortex.particles.map((particle) => ({
          angle: particle.angle,
          radius: particle.radius,
          y: particle.y,
          speed: particle.speed,
          vy: particle.vy,
          position: { x: particle.px, y: particle.py, z: particle.pz },
        })),
      };
    },
    readChamberConstructions(): ChamberConstruction[] {
      return chambers.map((chamber) => ({
        id: chamber.spec.id,
        height: chamber.spec.height,
        isAmber: chamber.spec.isAmber,
        constructedTimer: chamber.constructedTimer,
        indicators: [
          {
            color: RENDER_COLORS.indicatorReady,
            emissive: RENDER_COLORS.indicatorReady,
            emissiveIntensity: 0.8,
            position: {
              x: 0,
              y: chamber.spec.height - 0.45 + 0.12,
              z: -chamber.spec.depth / 2,
            },
          },
          {
            color: RENDER_COLORS.indicatorReady,
            emissive: RENDER_COLORS.indicatorReady,
            emissiveIntensity: 0.8,
            position: {
              x: 0,
              y: chamber.spec.height - 0.45 + 0.12,
              z: chamber.spec.depth / 2,
            },
          },
        ],
        jets: [0, 1, 2, 3].map((index) => ({
          opacity: 0,
          color: chamber.spec.isAmber ? RENDER_COLORS.jetAmber : RENDER_COLORS.jetMain,
          blending: 2,
          position: {
            x: index % 2 === 0 ? -0.45 : 0.45,
            y: chamber.spec.height - 0.5,
            z: -chamber.spec.depth * 0.25 + Math.floor(index / 2) * chamber.spec.depth * 0.5,
          },
        })),
        innerLight: {
          intensity: 0.4,
          color: chamber.spec.isAmber ? RENDER_COLORS.innerLightAmber : RENDER_COLORS.innerLightMain,
          distance: 4.0,
          position: { x: 0, y: chamber.spec.height - 0.4, z: 0 },
        },
        labelSprite: {
          isAmber: chamber.spec.isAmber,
          scale: { x: 4.6, y: 1.72, z: 1 },
          position: { x: 0, y: chamber.spec.height + 1.2, z: 0 },
        },
      }));
    },
    readSeedState(): number {
      return seedAfterBuild;
    },
  };
}
