// Declared float tolerance: the fixture generator and this port both round to 6
// decimal digits, so replay comparisons are exact at that precision.
const ROUND_DIGITS = 6;
const round = (value: number, digits = ROUND_DIGITS): number =>
  Math.round(value * 10 ** digits) / 10 ** digits + 0;

export function createLcg(seed: number): { random: () => number; seed: () => number } {
  let state = seed >>> 0;
  return {
    random: () => {
      state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
      return state / 2 ** 32;
    },
    seed: () => state,
  };
}

