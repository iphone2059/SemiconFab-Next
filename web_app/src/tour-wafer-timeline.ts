interface SplinePoint {
  x: number;
  y: number;
  z: number;
}

/** Frozen getCatmullRomSplinePoint (twin.html:18195-18213). */
export function getCatmullRomSplinePoint(
  p0: SplinePoint,
  p1: SplinePoint,
  p2: SplinePoint,
  p3: SplinePoint,
  u: number,
): SplinePoint {
  const u2 = u * u;
  const u3 = u2 * u;
  return {
    x:
      0.5 *
      (2 * p1.x +
        (-p0.x + p2.x) * u +
        (2 * p0.x - 5 * p1.x + 4 * p2.x - p3.x) * u2 +
        (-p0.x + 3 * p1.x - 3 * p2.x + p3.x) * u3),
    y: 2.5,
    z:
      0.5 *
      (2 * p1.z +
        (-p0.z + p2.z) * u +
        (2 * p0.z - 5 * p1.z + 4 * p2.z - p3.z) * u2 +
        (-p0.z + 3 * p1.z - 3 * p2.z + p3.z) * u3),
  };
}

const MAX_TRAIL_POINTS = 30;
const TRAIL_MIN_DISTANCE = 0.25;
const FOLLOW_CAMERA_OFFSET = { x: 0, y: 6.0, z: -8.0 } as const;

export function createWaferTimeline(scenario: WaferScenario): WaferTimeline {
  const clockStartMs = scenario.clockStartMs;
  const hudLanguage = scenario.hudLanguage;
  let isZh = hudLanguage.startsWith('zh');

  let clockMs = clockStartMs;
  let tick = 0;
  let lastFrameTimeMs = clockStartMs;
  let lastDt = 0;

  let product = scenario.product;
  let speed = scenario.speed;
  let route: readonly WaferRouteWaypoint[] = scenario.products[scenario.product];
  let playing = true;
  let index = 0;
  let stepTimer = 0;
  let position: Vec3 = { x: 0, y: 2.5, z: 0 };
  let rotationY = 0;
  const camera: Vec3 = cloneVec(scenario.initialCamera);
  const trail: Vec3[] = [];
  let trailVisible = false;
  let drawRange = 0;
  let trailMax = 0;

  let completed = false;
  let completionTimeMs: number | null = null;
  let actionCount = 0;
  let maxObservedDt = 0;
  let stalledFrameIndex = -1;

  const events: WaferEvent[] = [];

  const firstWaypoint = route[0];
  if (firstWaypoint !== undefined) {
    position = { x: firstWaypoint.x, y: 2.5, z: firstWaypoint.z };
  }

  const computeHud = (): WaferHud => {
    const total = route.length;
    const clamped = Math.min(index, total - 1);
    const current = route[clamped];
    const bay =
      current !== undefined
        ? scenario.categoryBays[current.category] ?? { nameEn: '', nameZh: '' }
        : { nameEn: '', nameZh: '' };
    const lastIndex = total - 1;
    let status: string;
    if (clamped === lastIndex && !playing) {
      status = isZh ? '路线完成' : 'Route complete';
    } else if (playing) {
      status = isZh ? '晶圆流转中...' : 'Navigating...';
    } else {
      status = isZh ? '已暂停' : 'Paused';
    }
    return {
      step: (isZh ? '步骤 ' : 'Step ') + String(current === undefined ? 0 : current.step) + '/' + String(total),
      width: (((current === undefined ? 0 : current.step) / total) * 100).toFixed(1) + '%',
      toolGroup: current === undefined ? '' : current.tool_group,
      recipe: current === undefined || current.recipe === null || current.recipe === '' ? '—' : current.recipe,
      bay: isZh ? bay.nameZh + ' (' + bay.nameEn + ')' : bay.nameEn + ' (' + bay.nameZh + ')',
      status,
      badge: 'Product ' + product + ' · ' + String(total) + ' Steps',
    };
  };

  let hud = computeHud();

  const updateTrailMesh = (): void => {
    if (trail.length < 2) {
      trailVisible = false;
      return;
    }
    trailVisible = true;
    drawRange = trail.length;
  };

  const clearTrail = (): void => {
    trail.length = 0;
    trailVisible = false;
    drawRange = 0;
  };

  const recordTrailPoint = (point: Vec3): void => {
    const last = trail[trail.length - 1];
    if (last === undefined || Math.hypot(point.x - last.x, point.y - last.y, point.z - last.z) > TRAIL_MIN_DISTANCE) {
      trail.push(cloneVec(point));
      if (trail.length > MAX_TRAIL_POINTS) trail.shift();
      trailMax = Math.max(trailMax, trail.length);
      updateTrailMesh();
    }
  };

  const snapshot = (): WaferDiscreteSnapshot => ({
    playing,
    product,
    speed,
    index,
    hud,
    trailVisible,
    trailCount: trail.length,
    drawRange,
  });

  const emitDiff = (before: WaferDiscreteSnapshot, after: WaferDiscreteSnapshot): void => {
    if (after.playing !== before.playing) {
      events.push({ timeMs: clockMs, tick, type: 'playing', playing: after.playing });
    }
    if (after.product !== before.product) {
      events.push({ timeMs: clockMs, tick, type: 'product', product: after.product });
    }
    if (after.speed !== before.speed) {
      events.push({ timeMs: clockMs, tick, type: 'speed', speed: after.speed });
    }
    if (after.index !== before.index) {
      events.push({ timeMs: clockMs, tick, type: 'index', index: after.index });
    }
    if (
      after.hud.step !== before.hud.step ||
      after.hud.width !== before.hud.width ||
      after.hud.toolGroup !== before.hud.toolGroup ||
      after.hud.recipe !== before.hud.recipe ||
      after.hud.bay !== before.hud.bay ||
      after.hud.status !== before.hud.status ||
      after.hud.badge !== before.hud.badge
    ) {
      events.push({ timeMs: clockMs, tick, type: 'hud', hud: after.hud });
    }
    if (
      after.trailVisible !== before.trailVisible ||
      after.trailCount !== before.trailCount ||
      after.drawRange !== before.drawRange
    ) {
      events.push({
        timeMs: clockMs,
        tick,
        type: 'trail',
        visible: after.trailVisible,
        count: after.trailCount,
        drawRange: after.drawRange,
      });
    }
  };

  const isRouteCompletion = (before: WaferDiscreteSnapshot, after: WaferDiscreteSnapshot): boolean =>
    before.playing === true &&
    after.playing === false &&
    index === route.length - 1 &&
    stepTimer === 0;

  const finishRoute = (): void => {
    completed = true;
    completionTimeMs = clockMs;
    events.push({ timeMs: clockMs, tick, type: 'complete', index });
  };

  const frameStep = (dt: number): void => {
    if (playing) {
      const duration = 2.0 / speed;
      stepTimer += dt;
      const progress = Math.min(stepTimer / duration, 1.0);
      let currentPosition: Vec3;
      let dx = 0;
      let dz = 0;
      if (index === 0) {
        currentPosition = { x: route[0].x, y: 2.5, z: route[0].z };
      } else {
        const p0 = route[Math.max(0, index - 2)];
        const p1 = route[index - 1];
        const p2 = route[index];
        const p3 = route[Math.min(route.length - 1, index + 1)];
        if (progress < 0.75) {
          const u = progress / 0.75;
          currentPosition = getCatmullRomSplinePoint(p0, p1, p2, p3, u);
          const nextU = Math.min(u + 0.02, 1.0);
          const nextPosition = getCatmullRomSplinePoint(p0, p1, p2, p3, nextU);
          dx = nextPosition.x - currentPosition.x;
          dz = nextPosition.z - currentPosition.z;
        } else {
          currentPosition = { x: p2.x, y: 2.5, z: p2.z };
        }
      }
      position = { x: currentPosition.x, y: currentPosition.y, z: currentPosition.z };
      if (dx * dx + dz * dz > 0.00001) {
        rotationY = Math.atan2(dx, dz);
      }
      recordTrailPoint(position);
      if (progress >= 1.0) {
        stepTimer = 0;
        if (index + 1 < route.length) {
          index += 1;
          hud = computeHud();
        } else {
          playing = false;
          hud = computeHud();
        }
      }
    }
    camera.x = position.x + FOLLOW_CAMERA_OFFSET.x;
    camera.y = position.y + FOLLOW_CAMERA_OFFSET.y;
    camera.z = position.z + FOLLOW_CAMERA_OFFSET.z;
  };

  const readFrame = (): WaferFrame => {
    const stepDurationSeconds = 2.0 / speed;
    const progress = Math.min(stepTimer / stepDurationSeconds, 1.0);
    const lastIndex = route.length - 1;
    let segment: WaferSegment;
    if (!playing) {
      segment = index === lastIndex && stepTimer === 0 ? 'complete' : 'paused';
    } else if (index === 0) {
      segment = 'start';
    } else {
      segment = progress < 0.75 ? 'transit' : 'dwell';
    }
    return {
      tick,
      timeMs: clockMs,
      dt: round(lastDt),
      playing,
      product,
      speed,
      index,
      stepTimer: round(stepTimer),
      stepDurationSeconds: round(stepDurationSeconds),
      progress: round(progress),
      segment,
      waypointCount: route.length,
      position: roundVec(position),
      rotationY: round(rotationY),
      trailVisible,
      trailCount: trail.length,
      drawRange,
      hud,
      camera: roundVec(camera),
    };
  };

  const initialFrame = readFrame();

  const applyAction = (event: WaferEvent): void => {
    actionCount += 1;
    events.push(event);
  };

  return {
    get clockMs() {
      return clockMs;
    },
    get tick() {
      return tick;
    },
    step(dtMs: number): void {
      const nowMs = clockMs + dtMs;
      const dt = Math.min((nowMs - lastFrameTimeMs) / 1000, 0.1);
      lastFrameTimeMs = nowMs;
      clockMs = nowMs;
      tick += 1;
      lastDt = dt;
      maxObservedDt = Math.max(maxObservedDt, dt);
      if (dt === 0.1 && stalledFrameIndex === -1) stalledFrameIndex = tick;
      const before = snapshot();
      frameStep(dt);
      const after = snapshot();
      emitDiff(before, after);
      if (!completed && isRouteCompletion(before, after)) {
        finishRoute();
      }
    },
    togglePlay(): void {
      const before = snapshot();
      playing = !playing;
      lastFrameTimeMs = clockMs;
      hud = computeHud();
      const after = snapshot();
      applyAction({ timeMs: clockMs, tick, type: 'action', action: playing ? 'resume' : 'pause' });
      emitDiff(before, after);
    },
    setSpeed(nextSpeed: number): void {
      const before = snapshot();
      speed = nextSpeed;
      const after = snapshot();
      applyAction({ timeMs: clockMs, tick, type: 'action', action: 'speed', arg: nextSpeed });
      emitDiff(before, after);
    },
    replay(): void {
      const before = snapshot();
      completed = false;
      completionTimeMs = null;
      index = 0;
      stepTimer = 0;
      clearTrail();
      playing = true;
      const first = route[0];
      if (first !== undefined) position = { x: first.x, y: 2.5, z: first.z };
      hud = computeHud();
      const after = snapshot();
      applyAction({ timeMs: clockMs, tick, type: 'action', action: 'replay' });
      emitDiff(before, after);
    },
    setProduct(nextProduct: string): void {
      const before = snapshot();
      completed = false;
      completionTimeMs = null;
      product = nextProduct;
      route = scenario.products[nextProduct];
      index = 0;
      stepTimer = 0;
      clearTrail();
      playing = true;
      const first = route[0];
      if (first !== undefined) position = { x: first.x, y: 2.5, z: first.z };
      hud = computeHud();
      const after = snapshot();
      applyAction({ timeMs: clockMs, tick, type: 'action', action: 'product', arg: nextProduct });
      emitDiff(before, after);
    },
    setLanguage(language): void {
      const before = snapshot();
      isZh = language.startsWith('zh');
      hud = computeHud();
      emitDiff(before, snapshot());
    },
    open(): void {
      if (index >= route.length - 1) { this.replay(); return; }
      playing = true;
      const point = route[index];
      if (point) position = { x: point.x, y: 2.5, z: point.z };
      hud = computeHud();
    },
    close(): void {
      playing = false;
      clearTrail();
      hud = computeHud();
    },
    readFrame,
    readInitialFrame(): WaferFrame {
      return initialFrame;
    },
    readEvents(): WaferEvent[] {
      return events.slice();
    },
    readTrailPoints(): Vec3[] {
      // Frozen updateWaferTrailMesh only uploads the first drawRange points and
      // hides the line entirely below two points (drawRange stays 0).
      return trail.slice(0, drawRange).map((point) => ({
        x: Math.fround(point.x),
        y: Math.fround(point.y),
        z: Math.fround(point.z),
      }));
    },
    readStats(): WaferStats {
      return {
        events: events.length,
        speed: scenario.speed,
        stepDurationSeconds: round(2.0 / scenario.speed),
        completed,
        completionTimeMs,
        finalIndex: index,
        finalProduct: product,
        finalSpeed: speed,
        waypointCount: route.length,
        trailMax,
        durationMs: completionTimeMs === null ? null : completionTimeMs - clockStartMs,
        actionCount,
        maxObservedDt,
        stalledFrameIndex,
      };
    },
  };
}
