// Literal port of the frozen original Cinematic Tour and Wafer-follow controllers
// (twin.html b3666132: Tour 19302-19655, Wafer follow 18058-18608, plus the two
// inline frozen helpers setFabLevelQuiet and getCatmullRomSplinePoint).
//
// Pure timing/state only: the renderer maps these values onto the camera, the FOUP
// mesh and the HUD DOM. No DOM, THREE, Date.now, Math.random, real timers or real
// RAF; time comes from the injected clock / frame step and all waypoints/routes are
// injected data. The vector fixture
// web_app/tests/fixtures/original-tour-wafer-vectors.json is generated by
// the frozen motion fixture, which executes the frozen source slices
// inside node:vm with the same declared deterministic scheduler.
//
// Frozen timing is represented exactly as the original represents it:
// - Tour: tweenCamera RAF easing + a 100 ms setInterval dwell countdown; next/prev
//   clear timers and jump waypoints. There is no seek in the frozen Tour.
// - Wafer: updateWaferFollowFrame derives dt = min((now - lastFrame) / 1000, 0.1)
//   each frame; speed 1x/4x/16x scales dur = 2.0 / speed; replay/product changes
//   reset index/stepTimer/trail; there is no seek in the frozen wafer flow.

export interface Vec3 {
  x: number;
  y: number;
  z: number;
}

const ROUND_DIGITS = 6;

/** Declared float tolerance: fixtures and controllers round to 6 decimals. */
const round = (value: number, digits = ROUND_DIGITS): number =>
  Math.round(value * 10 ** digits) / 10 ** digits + 0;

function roundVec(vec: Vec3): Vec3 {
  return { x: round(vec.x), y: round(vec.y), z: round(vec.z) };
}

function cloneVec(vec: Vec3): Vec3 {
  return { x: vec.x, y: vec.y, z: vec.z };
}

function lerpVec(from: Vec3, to: Vec3, alpha: number): Vec3 {
  return {
    x: from.x + (to.x - from.x) * alpha,
    y: from.y + (to.y - from.y) * alpha,
    z: from.z + (to.z - from.z) * alpha,
  };
}

