interface ScheduledEntry {
  due: number;
  sequence: number;
  kind: 'raf' | 'interval';
  id?: number;
  delay?: number;
  callback: (nowMs: number) => void;
  cancelled?: boolean;
}

export function createTourTimeline(scenario: TourScenario): TourTimeline {
  const waypoints = scenario.waypoints;
  let clockMs = scenario.clockStartMs;
  let tick = 0;

  let active = false;
  let index = 0;
  let level = scenario.initialLevel;
  let timerText = '';
  let progressWidth = '';
  let hudTag = '';
  let hudTitle = '';
  let activeDot = -1;
  let camera = cloneVec(scenario.initialCamera);
  let target = cloneVec(scenario.initialTarget);

  let countdownId: number | null = null;
  let holdStartMs = 0;
  let activeCameraAnimId = 0;
  let nextTimerId = 1;
  const timers = new Map<number, { kind: 'interval'; delay: number }>();
  let queue: ScheduledEntry[] = [];
  let sequence = 0;

  const events: TourEvent[] = [];
  const counters = { starts: 0, stops: 0, nexts: 0, prevs: 0 };
  let lastDeactivatedAtMs: number | null = null;
  const hudLanguage = scenario.hudLanguage;

  const phase = (): TourPhase => {
    if (!active) return 'IDLE';
    return countdownId === null ? 'TWEEN' : 'HOLD';
  };

  const snapshot = (): TourDiscreteSnapshot => ({
    active,
    index,
    phase: phase(),
    level,
    timerText,
    progressWidth,
    hudTag,
    hudTitle,
    activeDot,
  });


  let previous = snapshot();

  const pushEvent = (event: TourEvent): void => {
    events.push(event);
  };

  const emitDiff = (timeMs: number): void => {
    const current = snapshot();
    if (current.active !== previous.active) {
      pushEvent({ timeMs, type: 'active', active: current.active });
      if (!current.active) lastDeactivatedAtMs = timeMs;
    }
    if (current.index !== previous.index) {
      const waypoint = waypoints[current.index];
      pushEvent({
        timeMs,
        type: 'waypoint',
        index: current.index,
        tag: waypoint ? waypoint.tag : null,
        titleEn: waypoint ? waypoint.titleEn : null,
        level: current.level,
        durationMs: waypoint ? waypoint.durationMs : null,
        holdDurationMs: waypoint ? waypoint.holdDurationMs : null,
      });
    }
    if (current.phase !== previous.phase) {
      pushEvent({ timeMs, type: 'phase', phase: current.phase });
    }
    if (current.level !== previous.level) {
      pushEvent({ timeMs, type: 'level', level: current.level });
    }
    if (
      current.timerText !== previous.timerText ||
      current.progressWidth !== previous.progressWidth
    ) {
      pushEvent({ timeMs, type: 'timer', text: current.timerText, width: current.progressWidth });
    }
    previous = current;
  };

  const clearTimers = (): void => {
    if (countdownId !== null) {
      clearTimer(countdownId);
      countdownId = null;
    }
  };

  const clearTimer = (id: number): void => {
    timers.delete(id);
    for (const entry of queue) {
      if (entry.id === id) entry.cancelled = true;
    }
  };

  const scheduleRaf = (callback: (nowMs: number) => void): void => {
    // Floating-point frame boundaries can make floor(clock/frame)+1 land exactly on
    // clockMs; a due<=now RAF would then be processed forever inside one step.
    const frameIndex = Math.floor((clockMs + 1e-9) / scenario.frameMs);
    let due = (frameIndex + 1) * scenario.frameMs;
    if (!(due > clockMs + 1e-9)) due = clockMs + scenario.frameMs;
    queue.push({ due, sequence: sequence++, kind: 'raf', callback });
  };

  const scheduleInterval = (callback: (nowMs: number) => void, delay: number): number => {
    const id = nextTimerId++;
    timers.set(id, { kind: 'interval', delay });
    queue.push({ due: clockMs + delay, sequence: sequence++, kind: 'interval', id, delay, callback });
    return id;
  };

  const advanceTo = (targetMs: number): void => {
    for (;;) {
      let best: ScheduledEntry | null = null;
      for (const entry of queue) {
        if (entry.cancelled) continue;
        if (
          best === null ||
          entry.due < best.due ||
          (entry.due === best.due && entry.sequence < best.sequence)
        ) {
          best = entry;
        }
      }
      if (best === null || best.due > targetMs + 1e-9) break;
      queue = queue.filter((entry) => entry !== best);
      clockMs = Math.max(clockMs, best.due);
      if (best.kind === 'interval') best.due = clockMs + (best.delay ?? 0);
      best.callback(clockMs);
      emitDiff(clockMs);
      if (best.kind === 'interval' && best.id !== undefined && timers.has(best.id) && !best.cancelled) {
        queue.push(best);
      }
    }
    clockMs = Math.max(clockMs, targetMs);
  };

  const playWaypoint = (nextIndex: number): void => {
    if (!active) return;
    clearTimers();
    if (nextIndex >= waypoints.length) {
      stopTour();
      return;
    }
    const clampedIndex = nextIndex < 0 ? 0 : nextIndex;
    index = clampedIndex;
    const waypoint = waypoints[clampedIndex];
    level = waypoint.level;
    hudTag = waypoint.tag;
    hudTitle = hudLanguage === 'zh-CN' ? waypoint.titleZh : waypoint.titleEn;
    timerText = '5s';
    progressWidth = '100%';
    activeDot = clampedIndex;

    const animId = ++activeCameraAnimId;
    const startPos = cloneVec(camera);
    const endPos = cloneVec(waypoint.cameraPos);
    const startTarget = cloneVec(target);
    const endTarget = cloneVec(waypoint.lookAt);
    const startTime = clockMs;
    const animateTween = (nowMs: number): void => {
      if (animId !== activeCameraAnimId) return;
      const elapsed = nowMs - startTime;
      const progress = Math.min(elapsed / waypoint.durationMs, 1);
      const ease = 0.5 - Math.cos(progress * Math.PI) / 2;
      camera = lerpVec(startPos, endPos, ease);
      target = lerpVec(startTarget, endTarget, ease);
      if (progress < 1) {
        scheduleRaf(animateTween);
      } else {
        onTweenComplete();
      }
    };
    const onTweenComplete = (): void => {
      if (!active) return;
      clearTimers();
      const totalDwellMs = waypoint.holdDurationMs || 5000;
      holdStartMs = clockMs;
      timerText = '5s';
      progressWidth = '100%';
      countdownId = scheduleInterval(() => {
        if (!active) {
          clearTimers();
          return;
        }
        const elapsed = clockMs - holdStartMs;
        const remaining = Math.max(0, totalDwellMs - elapsed);
        const secs = Math.ceil(remaining / 1000);
        const fraction = remaining / totalDwellMs;
        timerText = String(secs) + 's';
        progressWidth = String(Math.max(0, Math.min(100, fraction * 100))) + '%';
        if (remaining <= 0) {
          clearTimers();
          if (index + 1 >= waypoints.length) {
            stopTour();
            return;
          }
          playWaypoint(index + 1);
        }
      }, scenario.countdownIntervalMs);
    };
    scheduleRaf(animateTween);
  };

  const startTour = (): void => {
    active = true;
    index = 0;
    clearTimers();
    playWaypoint(0);
  };

  const stopTour = (): void => {
    active = false;
    clearTimers();
    activeCameraAnimId += 1;
  };

  const initialFrame = readFrame();

  function readFrame(): TourFrame {
    return {
      tick,
      timeMs: clockMs,
      active,
      index,
      phase: phase(),
      level,
      timerText,
      progressWidth,
      hudTag,
      hudTitle,
      activeDot,
      camera: roundVec(camera),
      target: roundVec(target),
    };
  }

  return {
    get tick() {
      return tick;
    },
    get clockMs() {
      return clockMs;
    },
    start(): void {
      counters.starts += 1;
      const before = snapshot();
      startTour();
      pushEvent({ timeMs: clockMs, type: 'action', action: 'start' });
      previous = before;
      emitDiff(clockMs);
    },
    stop(): void {
      counters.stops += 1;
      const before = snapshot();
      stopTour();
      pushEvent({ timeMs: clockMs, type: 'action', action: 'stop' });
      previous = before;
      emitDiff(clockMs);
    },
    next(): void {
      counters.nexts += 1;
      const before = snapshot();
      if (active) {
        clearTimers();
        if (index + 1 >= waypoints.length) {
          stopTour();
        } else {
          playWaypoint(index + 1);
        }
      }
      pushEvent({ timeMs: clockMs, type: 'action', action: 'next' });
      previous = before;
      emitDiff(clockMs);
    },
    prev(): void {
      counters.prevs += 1;
      const before = snapshot();
      if (active) {
        clearTimers();
        const previousIndex = (index - 1 + waypoints.length) % waypoints.length;
        playWaypoint(previousIndex);
      }
      pushEvent({ timeMs: clockMs, type: 'action', action: 'prev' });
      previous = before;
      emitDiff(clockMs);
    },
    step(): void {
      tick += 1;
      const frameTime = scenario.clockStartMs + tick * scenario.frameMs;
      advanceTo(frameTime);
    },
    readFrame,
    readInitialFrame(): TourFrame {
      return initialFrame;
    },
    readEvents(): TourEvent[] {
      return events.slice();
    },
    readStats(): TourStats {
      return {
        events: events.length,
        waypointAdvances: events.filter((event) => event.type === 'waypoint').length,
        phaseTransitions: events.filter((event) => event.type === 'phase').length,
        timerUpdates: events.filter((event) => event.type === 'timer').length,
        levelChanges: events.filter((event) => event.type === 'level').length,
        starts: counters.starts,
        stops: counters.stops,
        nexts: counters.nexts,
        prevs: counters.prevs,
        completedAtMs: lastDeactivatedAtMs,
        finalIndex: index,
        finalActive: active,
        waypointCount: waypoints.length,
      };
    },
  };
}

