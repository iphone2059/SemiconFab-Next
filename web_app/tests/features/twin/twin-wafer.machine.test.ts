import { createActor } from 'xstate';
import { expect, it } from 'vitest';
import { twinWaferMachine } from '@/twin/twin-wafer.machine';
it('owns route readiness, playback transitions and retained discrete progress', () => {
  const actor = createActor(twinWaferMachine);
  actor.start();
  expect(actor.getSnapshot().matches('closed')).toBe(true);
  actor.send({ type: 'RESTORE', product: 'B', speed: 16 });
  actor.send({ type: 'OPEN' });
  expect(actor.getSnapshot().matches('loading')).toBe(true);
  actor.send({ type: 'ROUTES_READY' });
  expect(actor.getSnapshot().matches('playing')).toBe(true);
  expect(actor.getSnapshot().context).toMatchObject({ product: 'B', speed: 16, index: 0, routesReady: true });
  actor.send({ type: 'WAYPOINT', index: 2 });
  actor.send({ type: 'TOGGLE' });
  expect(actor.getSnapshot().matches('paused')).toBe(true);
  actor.send({ type: 'SPEED', speed: 4 });
  expect(actor.getSnapshot().context.speed).toBe(4);
  actor.send({ type: 'PRODUCT', product: 'C' });
  expect(actor.getSnapshot().matches('playing')).toBe(true);
  expect(actor.getSnapshot().context).toMatchObject({ product: 'C', index: 0, speed: 4 });
  actor.send({ type: 'COMPLETE' });
  expect(actor.getSnapshot().matches('completed')).toBe(true);
  actor.send({ type: 'CLOSE' });
  expect(actor.getSnapshot().matches('closed')).toBe(true);
  expect(actor.getSnapshot().context).toMatchObject({ product: 'C', speed: 4, index: 0, routesReady: true });
  actor.send({ type: 'OPEN' });
  expect(actor.getSnapshot().matches('playing')).toBe(true);
  actor.stop();
});
it('retains route readiness when routes load before playback opens', () => {
  const actor = createActor(twinWaferMachine);
  actor.start();
  actor.send({ type: 'ROUTES_READY' });
  expect(actor.getSnapshot().matches('closed')).toBe(true);
  actor.send({ type: 'OPEN' });
  expect(actor.getSnapshot().matches('playing')).toBe(true);
  actor.stop();
});
