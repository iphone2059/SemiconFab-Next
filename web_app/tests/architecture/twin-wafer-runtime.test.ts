import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';
const sourceRoot = fileURLToPath(new URL('../../src/', import.meta.url));
const read = (path: string): string => readFileSync(join(sourceRoot, path), 'utf8');
it('keeps the Wafer Actor, timeline, RAF and scene writes inside TwinWaferRuntime', () => {
  const hook = read('twin/use-wafer-playback.ts');
  const runtime = read('twin/twin-wafer-runtime.ts');
  const machine = read('twin/twin-wafer.machine.ts');
  const page = read('twin/twin-page.tsx');
  expect(hook).not.toMatch(/requestAnimationFrame|cancelAnimationFrame|createWaferTimeline|WaferTimeline|rafHandle|timelineRef|performance\.now/);
  expect(runtime).toContain('createActor(twinWaferMachine)');
  expect(runtime).toContain('Scope.addFinalizer');
  expect(runtime).toContain('Scope.close(this.scope');
  expect(runtime).toContain('requestFrame');
  expect(runtime).toContain('cancelFrame');
  expect(runtime).toContain('this.generation === session.generation');
  expect(runtime).toContain('setWaferPoint');
  expect(runtime).toContain('setWaferTrail');
  expect(runtime).toContain('setCameraPose');
  expect(runtime).toContain('twinWaferActions.projectionSet');
  expect(runtime).toContain('twinWaferActions.hudSet');
  expect(page).toContain('const playbackScopeKey = `${site?.siteId ?? \'\'}:${selectedFabId ?? \'\'}:${viewerEpoch ?? \'\'}`');
  expect(page).toContain('scopeKey: playbackScopeKey');
  expect(machine).toContain("initial: 'closed'");
  expect(machine).toContain('loading:');
  expect(machine).toContain('playing:');
  expect(machine).toContain('paused:');
  expect(machine).toContain('completed:');
});
it('keeps Wafer process state outside TwinUiState and exposes only its Atom projection', () => {
  const state = read('twin/twin-state.ts');
  const atom = read('twin/twin-wafer.atom.ts');
  const slices = read('twin/use-twin-slices.ts');
  const hud = read('twin/twin-wafer-hud.tsx');
  expect(state).not.toContain('wafer: {');
  expect(state).not.toContain("type: 'wafer/");
  expect(atom).toContain('TwinWaferProjection');
  expect(atom).toContain('TwinWaferProcessProjection');
  expect(slices).toContain('twinWaferAtom');
  expect(slices).toContain('state => state.active');
  expect(hud).toContain('state) => state.playing');
  expect(hud).toContain('state) => state.speed');
});
it('stops Wafer when another process or presentation mode takes ownership', () => {
  const tourHook = read('twin/use-tour-controller.ts');
  const actions = read('twin/use-twin-actions.ts');
  const routeState = read('twin/use-twin-route-state.ts');
  expect(tourHook).toContain('stopTwinWaferRuntime(registry)');
  expect(actions).toContain('stopTwinWaferRuntime(registry)');
  expect(routeState).toContain('stopTwinWaferRuntime(registry)');
});
